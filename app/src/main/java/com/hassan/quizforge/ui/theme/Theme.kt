@Composable
fun QuizForgeTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    // Off by default: Material You's per-device "dynamic color" derives the whole palette from
    // the user's wallpaper, which on most Android 12+ phones would silently replace QuizForge's
    // actual brand colors (the indigo/teal/amber palette in Color.kt) with whatever happens to
    // match that phone's background - often muted grays that make the app look generic/unstyled
    // regardless of how the screens themselves are designed. Pass true explicitly if you'd
    // rather have the app blend in with the rest of a user's Material You phone instead.
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    val context = LocalContext.current
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S ->
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)

        darkTheme -> DarkColors
        else -> LightColors
    }

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            window.statusBarColor = colorScheme.primary.toArgb()
            WindowCompat.getInsetsController(window, view).isAppearanceLightStatusBars = !darkTheme
        }
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        shapes = QuizForgeShapes,
        content = content
    )
}
